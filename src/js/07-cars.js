/* Ширина машинки — по спрайту текущего скина: у повреждённого и у покрашенного
   она может отличаться от базового. */
function vehW(id, h) {
  /* У ригованной машинки ширину задаёт кузов, а не старый цельный спрайт: иначе
     хитбокс не совпадёт с картинкой. */
  if (car && car.id === id && car.rig) { var z = rigSize(car, h); if (z) return z.bw; }
  return sprW(id, h);
}

/* Единственная точка входа для машинки: 15 вызовов по всем экранам идут через неё,
   и риг (кузов + колёса отдельно) встроится сюда, не трогая ни одного из них.

   Поломка: колёса лежат на дороге отдельными спрайтами, а сам кузов садится на оси —
   опускаем его на высоту колёсной полосы и обрезаем по кромке дороги. Так не нужны
   скины _w1.._w4, у которых стирание колёс оставило вертикальные щели. */
/* Угол колеса. Формула отраслевая и без свободных параметров: путь делить на радиус.
   Копится по пройденному пути, поэтому колесо физически не может проскальзывать. */
var wheelA = 0;

/* Сборка машинки из частей. Колёса рисуются ПЕРЕД кузовом: у настоящего бокового
   вида арки перекрывают шину сверху, и порядок это показывает. */
/* Размеры сборки. Общая высота обязана равняться h — иначе ригованная машинка
   вырастет относительно остальных и разъедется с хитбоксом.
     bh + d*lift = h,  d = bw*tire2,  bw = bh*AR   ⇒   bh = h / (1 + AR*tire2*lift) */
function rigSize(car0, h) {
  var R = car0.rig, im = lazyImg(R.body);
  if (!ok(im)) { lazyImg(R.tire); return null; }   // ещё грузится — рисуем как раньше
  var ar = iw(im) / ih(im);
  var bh = h / (1 + ar * R.tire2 * R.lift);
  var bw = bh * ar;
  return { bw: bw, bh: bh, d: bw * R.tire2, im: im };
}

function drawRig(car0, x, y, h, o, miss) {
  var z = rigSize(car0, h);
  if (!z) return false;
  var R = car0.rig, bw = z.bw, bh = z.bh, d = z.d;
  var by = y - d * R.lift;                           // кузов приподнят над осями
  var rot = (o && o.rot) || 0;
  g.save();
  g.translate(x, y);
  if (rot) g.rotate(rot);
  if (o && o.alpha != null) g.globalAlpha = o.alpha;
  for (var i = 0; i < R.at.length; i++) {
    if (miss && i < miss) continue;                  // это колесо сейчас лежит на дороге
    var wx = (R.at[i] - 0.5) * bw;
    g.save();
    g.translate(wx, by - y);
    g.rotate(wheelA);
    spr(R.tire, 0, d / 2, d, { mid: false });
    g.restore();
  }
  spr(R.body, 0, by - y, bh, {});
  g.restore();
  return true;
}

function drawVehicle(id, x, y, h, o) {
  /* Ригованная машинка собирается из частей — так у неё крутятся колёса. */
  if (car && car.id === id && car.rig && !carPaint && damage === 0) {
    if (drawRig(car, x, y, h, o, noWheels ? Math.min(2, missWheels) : 0)) return;
  }
  if (!noWheels) { spr(id, x, y, h, o || {}); return; }
  var band = (WHEEL_BAND[id] || 0.2) * h * (Math.min(4, Math.max(1, missWheels)) / 4);
  g.save();
  g.beginPath(); g.rect(x - h * 2, y - h * 3, h * 4, h * 3 + band * 0.35); g.clip();
  spr(id, x, y + band, h, o || {});
  g.restore();
}

