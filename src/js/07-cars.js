function ixById(list, id, dflt) { for (var i = 0; i < list.length; i++) if (list[i].id === id) return i; return dflt || 0; }
/* Сохранённый выбор: новый формат — id, старый — индекс в ПОЛНОМ списке. Скрытый пункт → первый видимый. */
