def fnv(s):
    h = 0x811c9dc5
    for b in s.encode("utf-8"):
        h ^= b
        h = (h * 0x01000193) & 0xFFFFFFFF
    return format(h, "08x")


def tts(text, voice, path):
    req = urllib.request.Request(MODEL, data=json.dumps(
        {"text": text, "voice": voice, "stability": 0.3, "similarity_boost": 0.75,
         "style": 0.75, "speed": 0.95}).encode(),
        headers={"Authorization": "Key " + KEY, "Content-Type": "application/json"})
    r = json.load(urllib.request.urlopen(req, timeout=300))
    with urllib.request.urlopen(r["audio"]["url"], timeout=180) as src, open(path, "wb") as f:
        f.write(src.read())


